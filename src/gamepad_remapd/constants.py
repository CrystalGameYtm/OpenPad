"""Константи ядра Linux та канонічні (логічні) імена кнопок.

Числові коди взято з `linux/input-event-codes.h`, `linux/uinput.h` та
`linux/input.h`. Вони є частиною стабільного ABI ядра, тому їх безпечно
дублювати тут: це дозволяє працювати на Linux взагалі без бібліотеки
`python-evdev` (менше залежностей, менше накладних витрат на гарячому шляху).
"""
from __future__ import annotations

# --------------------------------------------------------------------------
# Типи подій (struct input_event.type)
# --------------------------------------------------------------------------
EV_SYN = 0x00      # службові події: SYN_REPORT закриває «кадр» подій
EV_KEY = 0x01      # кнопки (0/1)
EV_ABS = 0x03      # абсолютні осі (стіки, тригери, hat)
EV_FF = 0x15       # Force Feedback (вібрація)
EV_UINPUT = 0x0101  # службовий тип uinput: запити FF upload/erase від ядра

SYN_REPORT = 0     # «кадр завершено — доставляй події споживачам»

# --------------------------------------------------------------------------
# Осі
# --------------------------------------------------------------------------
ABS_X, ABS_Y, ABS_Z = 0x00, 0x01, 0x02
ABS_RX, ABS_RY, ABS_RZ = 0x03, 0x04, 0x05
ABS_HAT0X, ABS_HAT0Y = 0x10, 0x11

# --------------------------------------------------------------------------
# Кнопки геймпада
# --------------------------------------------------------------------------
BTN_SOUTH = 0x130   # BTN_A
BTN_EAST = 0x131    # BTN_B
BTN_C = 0x132
BTN_NORTH = 0x133   # BTN_X у термінології ядра (так, історично X == NORTH)
BTN_WEST = 0x134    # BTN_Y у термінології ядра
BTN_Z = 0x135
BTN_TL = 0x136
BTN_TR = 0x137
BTN_TL2 = 0x138
BTN_TR2 = 0x139
BTN_SELECT = 0x13A
BTN_START = 0x13B
BTN_MODE = 0x13C
BTN_THUMBL = 0x13D
BTN_THUMBR = 0x13E
BTN_TRIGGER_HAPPY1 = 0x2C0  # «додаткові» кнопки: сюди ідуть M1–M6/C/Z

# --------------------------------------------------------------------------
# Force Feedback
# --------------------------------------------------------------------------
FF_RUMBLE = 0x50
FF_GAIN = 0x60
UI_FF_UPLOAD = 1
UI_FF_ERASE = 2

# --------------------------------------------------------------------------
# Канонічні діапазони виходу, у яких працює Pipeline.
# Backend сам перемасштабує їх у діапазони конкретного віртуального пристрою.
# --------------------------------------------------------------------------
STICK_MIN, STICK_MAX = -32768, 32767
TRIGGER_MIN, TRIGGER_MAX = 0, 255

# --------------------------------------------------------------------------
# Логічні (вихідні) імена кнопок. Саме ці імена пишуть у `button_map`.
# --------------------------------------------------------------------------
STANDARD_BUTTONS = ("A", "B", "X", "Y", "LB", "RB", "BACK", "START",
                    "GUIDE", "LS", "RS")
DPAD_BUTTONS = ("UP", "DOWN", "LEFT", "RIGHT")
# Додаткові кнопки: у XInput для них немає місця, на Linux віддаємо їх як
# BTN_TRIGGER_HAPPY1.. — Steam Input / SDL бачать їх як звичайні кнопки.
# ML/MR — бокові/задні «весла» (Switch-стиль, GameSir, 8BitDo). Додані В КІНЕЦЬ: коди вже наявних
# кнопок (M1..Z = BTN_TRIGGER_HAPPY1..8) лишаються тими самими.
EXTRA_BUTTONS = ("M1", "M2", "M3", "M4", "M5", "M6", "C", "Z", "ML", "MR")
# «Цифрові тригери»: натискання кнопки → повне віддавлення аналогового тригера.
ANALOG_BUTTON_TARGETS = ("LT", "RT")

ALL_TARGETS = (STANDARD_BUTTONS + DPAD_BUTTONS + EXTRA_BUTTONS
               + ANALOG_BUTTON_TARGETS)
