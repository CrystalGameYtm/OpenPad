"""Generator of udev rules for user access to hidraw and /dev/uinput.

Why: by default /dev/hidrawN and /dev/uinput belong to root. Running the daemon as root is a bad idea
(extra privileges for a service that listens on a socket and reads raw bytes from USB). The right way is to grant
access ONLY to the nodes that are needed.

Two mechanisms, both enabled:
  * TAG+="uaccess"        — systemd-logind grants an ACL to the current user of the local
                            session (seat). Works "out of the box" on a desktop, without groups.
  * GROUP="input", 0660   — for services/SSH/headless sessions without a seat (the user must
                            be in the `input` group: sudo usermod -aG input $USER).
Rule files MUST have a name with a number < 73 (uaccess is processed in 73-seat-late.rules).
"""
from __future__ import annotations

from typing import Dict, Iterable, List, Optional, Tuple
from ..i18n import tr

HEADER = ('# /etc/udev/rules.d/70-gamepad-remapd.rules\n'
            '# Generated by: gamepad-remapd udev-rules\n'
            '#\n'
            '# After changes:  sudo udevadm control --reload && sudo udevadm trigger --subsystem-match=hidraw\n'
            "# Check:          udevadm test $(udevadm info -q path -n /dev/hidraw0) 2>&1 | grep -i -E 'uaccess|GROUP|MODE'\n"
            '#                 getfacl /dev/hidraw0      (your user should be listed)\n')

UINPUT_RULE = ('# Virtual gamepad: creating devices through /dev/uinput.\n'
                 '# static_node=uinput — the node appears even before the module is loaded (so the permissions are already in place).\n'
                 'KERNEL=="uinput", SUBSYSTEM=="misc", OPTIONS+="static_node=uinput", TAG+="uaccess", GROUP="input", MODE="0660"\n')


def hidraw_rule(vid: str, pid: Optional[str], comment: str = "") -> str:
    """Rules for hidraw: USB and Bluetooth. VID/PID are hex strings (as in lsusb).

        A Bluetooth hidraw has no USB parent (no idVendor/idProduct), so we match by the HID device name
        `0005:<VID>:<PID>.<N>` (0005 = BUS_BLUETOOTH).
    """
    vid = vid.lower().zfill(4)
    match = f'ATTRS{{idVendor}}=="{vid}"'
    kernels = f"0005:{vid.upper()}:"
    if pid:
        pid = pid.lower().zfill(4)
        match += f', ATTRS{{idProduct}}=="{pid}"'
        kernels += f"{pid.upper()}.*"
    else:
        kernels += "*"
    access = 'TAG+="uaccess", GROUP="input", MODE="0660"'
    line = (f'SUBSYSTEM=="hidraw", SUBSYSTEMS=="usb", {match}, {access}\n'
            f'SUBSYSTEM=="hidraw", KERNELS=="{kernels}", {access}')
    return (f"# {comment}\n" if comment else "") + line + "\n"


def generate(pairs: Iterable[Tuple[str, Optional[str], str]]) -> str:
    """pairs: (vid, pid|None, comment). Duplicates are removed."""
    seen = set()
    parts: List[str] = [tr(HEADER), tr(UINPUT_RULE)]
    for vid, pid, comment in pairs:
        key = (vid.lower().zfill(4), (pid or "").lower().zfill(4) if pid else None)
        if key in seen:
            continue
        seen.add(key)
        parts.append(hidraw_rule(vid, pid, comment))
    return "\n".join(parts)


def pairs_from_layouts(layouts: Dict[str, object]) -> List[Tuple[str, Optional[str], str]]:
    out = []
    for lay in layouts.values():
        if getattr(lay, "vid", None) is None:
            continue
        for pid in getattr(lay, "pids", ()):       
            out.append((f"{lay.vid:04x}", f"{pid:04x}", lay.name))
    return out


def hide_rule(vid: str, pid: str, comment: str = "") -> str:
    """The rule "hide the original gamepad from programs": removes the gamepad markers
    (ID_INPUT_JOYSTICK...) from its evdev nodes, by which SDL, Steam, Chrome and libinput find them. The daemon is NOT broken by this: it reads
    hidraw/evdev by path, not through udev properties. Virtual devices (uinput, /devices/virtual) are not touched —
    otherwise our own virtual gamepad would be hidden too if it has the same VID:PID (output_kind=ds4).

    It does not hide /dev/hidrawN itself: SDL with HIDAPI reads hidraw directly. For such programs — the environment variable
    SDL_GAMECONTROLLER_IGNORE_DEVICES=0xVID/0xPID (see README).
    """
    vid, pid = vid.lower().zfill(4), pid.lower().zfill(4)
    return (tr('# {0} ({1}:{2}): programs see only the virtual gamepad\n'
               'SUBSYSTEM=="input", KERNEL=="event[0-9]*", DEVPATH!="/devices/virtual/*", ATTRS{{id/vendor}}=="{3}", ATTRS{{id/product}}=="{4}", ENV{{ID_INPUT_JOYSTICK}}="", ENV{{ID_INPUT_ACCELEROMETER}}="", ENV{{ID_INPUT_TOUCHPAD}}="", ENV{{LIBINPUT_IGNORE_DEVICE}}="1"\n'
               '# SDL with HIDAPI reads hidraw directly; for such games: SDL_GAMECONTROLLER_IGNORE_DEVICES=0x{5}/0x{6}\n', comment or tr('hide the original'), vid, pid, vid, pid, vid, pid))


def hide_hidraw_rule(vid: str, pid: str, group: str, comment: str = "") -> str:
    """Hides /dev/hidrawN itself from everyone except the `group` group (the daemon is started in it): removes the user's uaccess ACL.
    Needed for SDL with HIDAPI (emulators, SDL3 games) that read hidraw directly and hang/duplicate input.
    """
    vid, pid = vid.lower().zfill(4), pid.lower().zfill(4)
    hide = f'TAG-="uaccess", GROUP="{group}", MODE="0660"'
    return (tr('# {0} ({1}:{2}): access for the group {3} only\n'
               'SUBSYSTEM=="hidraw", SUBSYSTEMS=="usb", ATTRS{{idVendor}}=="{4}", ATTRS{{idProduct}}=="{5}", {6}\n'
               'SUBSYSTEM=="hidraw", KERNELS=="0005:{7}:{8}.*", {9}\n', comment or tr('hide hidraw'), vid, pid, group, vid, pid, hide, vid.upper(), pid.upper(), hide))


def generate_hide_hidraw(pairs: Iterable[Tuple[str, str, str]], group: str = "gamepad-remapd") -> str:
    seen, parts = set(), [
        tr('# /etc/udev/rules.d/71-gamepad-remapd-hide-hidraw.rules   (exactly 71: AFTER 70-gamepad-remapd.rules, before 73-seat-late)\n'
           '# Generated by: gamepad-remapd udev-rules --hide VID:PID --hidraw-group ') + group + tr('\n'
                                                                                               '# Keep 70-gamepad-remapd.rules and 69-...-hide.rules (without --hidraw-group) alongside this file.\n'
                                                                                               '# Once:  sudo groupadd -f {0}   (do NOT add yourself to this group!)\n'
                                                                                               '# Apply: sudo udevadm control --reload && sudo udevadm trigger --subsystem-match=hidraw ; reconnect the gamepad\n'
                                                                                               '# Run the daemon: sudo -g {1} -u $USER env PYTHONPATH=src python3 -m gamepad_remapd serve\n'
                                                                                               '# (the daemon has the group, your programs do not, so SDL/games cannot open the original hidraw)\n', group, group)]
    for vid, pid, comment in pairs:
        key = (vid.lower().zfill(4), pid.lower().zfill(4))
        if key not in seen:
            seen.add(key)
            parts.append(hide_hidraw_rule(vid, pid, group, comment))
    return "\n".join(parts)


def generate_hide(pairs: Iterable[Tuple[str, str, str]]) -> str:
    seen, parts = set(), [
        tr('# /etc/udev/rules.d/69-gamepad-remapd-hide.rules\n'
           '# Generated by: gamepad-remapd udev-rules --hide VID:PID\n'
           '# Number 69: after 60-input-id (which sets ID_INPUT_JOYSTICK) and BEFORE 70-uaccess (ACLs keyed on that property).\n'
           '# Apply: sudo udevadm control --reload && sudo udevadm trigger --subsystem-match=input\n'
           '# Then reconnect the gamepad. To undo: delete the file and repeat the trigger.\n')]
    for vid, pid, comment in pairs:
        key = (vid.lower().zfill(4), pid.lower().zfill(4))
        if key not in seen:
            seen.add(key)
            parts.append(hide_rule(vid, pid, comment))
    return "\n".join(parts)
